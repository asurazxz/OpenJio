test('Create a jio starts from a popular area or any searched place', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('openjio:onboarding:v1', 'done'))
  await page.goto('/signin')
  await page.getByRole('button', { name: /^Mei Lin/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: /, Mei\?/ })).toBeVisible()
  await page.goto('/new?mode=solo')
  await page.getByLabel('Name', { exact: true }).fill('Start anywhere')
  await page.getByRole('button', { name: 'Next' }).click()
  // Time inputs move in 5-minute steps and a typed value snaps to the nearest 5.
  await expect(page.locator('#st')).toHaveAttribute('step', '300')
  await page.locator('#st').fill('14:03')
  await page.locator('#st').dispatchEvent('change')
  await expect(page.locator('#st')).toHaveValue('14:05')
  await page.getByRole('button', { name: 'Next' }).click()
  await expect(page.getByText('Search any place, MRT station, address or postal code, or pick a popular area.')).toBeVisible()
  await page.getByRole('button', { name: 'Tampines', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Tampines', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Next' }).click()
  await expect(page.locator('.review')).toContainText('Around Tampines')
  await page.getByRole('button', { name: 'Create plan' }).click()
  await expect(page.getByText(/around tampines/i).first()).toBeVisible()
})

test('Create a jio explains when place search is unavailable', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('openjio:onboarding:v1', 'done'))
  await page.route('**/api/places/search*', (route) => route.abort())
  await page.goto('/signin')
  await page.getByRole('button', { name: /^Mei Lin/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: /, Mei\?/ })).toBeVisible()
  await page.goto('/new?mode=solo')
  await page.getByLabel('Name', { exact: true }).fill('Search down')
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByRole('button', { name: 'Next' }).click()
  await page.getByLabel('Start point').fill('Jewel')
  await expect(page.getByText("Search isn't available right now. Pick a popular area instead.")).toBeVisible()
  await page.getByRole('button', { name: 'Bugis', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Bugis', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('First-use guidance can be dismissed and replayed without leaving a backdrop', async ({ page }) => {
  await page.goto('/signin')
  await page.getByRole('button', { name: /^Mei Lin/ }).click()
  const guide = page.getByRole('dialog', { name: 'A quick look around' })
  await expect(guide).toBeVisible()
  await guide.getByRole('button', { name: 'Skip tour', exact: true }).click()
  await expect(guide).toBeHidden()
  await page.reload()
  await expect(guide).toBeHidden()
  await page.getByRole('button', { name: 'Quick tour', exact: true }).click()
  await expect(guide).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(guide).toBeHidden()
  await expect(page.locator('body')).toHaveCSS('opacity', '1')
})
